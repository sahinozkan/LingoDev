import 'package:cloud_firestore/cloud_firestore.dart';

import '../models/word_model.dart';

/// Repository for CRUD and spaced-repetition scheduling on a user's word collection.
///
/// Firestore path: `users/{userId}/words/{wordId}`
class WordRepository {
  WordRepository({required this.userId})
      : _wordsCollection = FirebaseFirestore.instance
            .collection('users')
            .doc(userId)
            .collection('words');

  final String userId;

  final CollectionReference<Map<String, dynamic>> _wordsCollection;

  /// Tek pratik oturumunda gösterilecek azami kelime sayısı.
  static const int dailySessionLimit = 20;

  // ---------------------------------------------------------------------------
  // READ
  // ---------------------------------------------------------------------------

  /// Real-time stream of all words, ordered by [createdAt] descending.
  Stream<List<WordModel>> watchWords() {
    return _wordsCollection
        .orderBy('createdAt', descending: true)
        .snapshots()
        .map((snapshot) => snapshot.docs.map(WordModel.fromFirestore).toList());
  }

  /// Real-time stream of a single word document.
  Stream<WordModel?> watchWord(String wordId) {
    return _wordsCollection.doc(wordId).snapshots().map((doc) {
      if (!doc.exists || doc.data() == null) return null;
      return WordModel.fromFirestore(doc);
    });
  }

  /// Fetches the words due for review right now (nextReviewAt <= Timestamp.now()).
  /// Capped at [dailySessionLimit], prioritizing the most overdue words first.
  Future<List<WordModel>> getDueWords() async {
    try {
      final snapshot = await _wordsCollection
          .where('nextReviewAt', isLessThanOrEqualTo: Timestamp.now())
          .orderBy('nextReviewAt')
          .limit(dailySessionLimit)
          .get();
      return snapshot.docs.map(WordModel.fromFirestore).toList();
    } catch (_) {
      // Fallback in case composite index / single field indexing order requires in-memory sorting
      final snapshot = await _wordsCollection
          .where('nextReviewAt', isLessThanOrEqualTo: Timestamp.now())
          .limit(dailySessionLimit)
          .get();
      final list = snapshot.docs.map(WordModel.fromFirestore).toList();
      list.sort((a, b) => (a.nextReviewAt ?? DateTime.now())
          .compareTo(b.nextReviewAt ?? DateTime.now()));
      return list;
    }
  }

  /// Counts the words due for review right now (used for the HomeView badge).
  Future<int> getDueCount() async {
    final aggregate = await _wordsCollection
        .where('nextReviewAt', isLessThanOrEqualTo: Timestamp.now())
        .count()
        .get();
    return aggregate.count ?? 0;
  }

  // ---------------------------------------------------------------------------
  // CREATE
  // ---------------------------------------------------------------------------

  /// Adds [word] to Firestore. The document ID is auto-generated by Firestore.
  ///
  /// Zaten aynı `english` değerine sahip bir kelime varsa (küçük harf + trim
  /// ile karşılaştırılır) eklemeyi atlar ve `false` döner. Kelime eklendiyse
  /// `true` döner.
  Future<bool> addWord(WordModel word) async {
    final normalized = word.english.toLowerCase().trim();

    final existingSnapshot = await _wordsCollection.get();
    final alreadyExists = existingSnapshot.docs.any(
      (doc) =>
          (doc.data()['english'] as String? ?? '').toLowerCase().trim() ==
          normalized,
    );

    if (alreadyExists) return false;

    await _wordsCollection.add(word.toFirestore());
    return true;
  }

  /// Paketten gelen kelimeleri kullanıcının koleksiyonuna KOPYALAR (referans değil).
  /// masteryLevel ve nextReviewAt kişiye özel alanlardır — aynı paketi alan her
  /// kullanıcının ilerlemesi farklı olacağından ortak paket dökümanına yazılamaz,
  /// her kullanıcı kendi kopyası üzerinden ilerler.
  /// Zaten mevcut olan kelimeler (english alanı, küçük harf + trim ile
  /// karşılaştırılır) atlanır ki kullanıcı aynı kelimeyi iki kez tekrar etmesin
  /// ve ilerlemesi bölünmesin. Gerçekten eklenen kelime sayısını döndürür.
  Future<int> importWords(List<WordModel> words) async {
    final existingSnapshot = await _wordsCollection.get();
    final existingEnglish = existingSnapshot.docs
        .map(
          (doc) =>
              (doc.data()['english'] as String? ?? '').toLowerCase().trim(),
        )
        .toSet();

    final newWords = words.where((word) {
      final normalized = word.english.toLowerCase().trim();
      return normalized.isNotEmpty && !existingEnglish.contains(normalized);
    }).toList();

    const batchWriteLimit = 500;
    for (var i = 0; i < newWords.length; i += batchWriteLimit) {
      final chunk = newWords.sublist(
        i,
        i + batchWriteLimit > newWords.length
            ? newWords.length
            : i + batchWriteLimit,
      );

      final batch = FirebaseFirestore.instance.batch();
      final now = Timestamp.now();
      for (final word in chunk) {
        batch.set(_wordsCollection.doc(), {
          'english': word.english,
          'turkish': word.turkish,
          'synonyms': word.synonyms,
          'antonyms': word.antonyms,
          'partOfSpeech': word.partOfSpeech,
          'exampleSentence': word.exampleSentence,
          'masteryLevel': 0,
          'nextReviewAt': now,
          'createdAt': now,
        });
      }
      await batch.commit();
    }

    return newWords.length;
  }

  // ---------------------------------------------------------------------------
  // UPDATE / SPACED REPETITION
  // ---------------------------------------------------------------------------

  /// Overwrites the Firestore document identified by [word.id].
  Future<void> updateWord(WordModel word) async {
    await _wordsCollection.doc(word.id).update(word.toFirestore());
  }

  /// Spaced Repetition (Aralıklı Tekrar) algoritması:
  ///
  /// - BİLDİM (correct = true):
  ///   masteryLevel 1 artar (maksimum 5).
  ///   Yeni nextReviewAt:
  ///     Seviye 1: +2 gün
  ///     Seviye 2: +4 gün
  ///     Seviye 3: +7 gün
  ///     Seviye 4: +14 gün
  ///     Seviye 5: null (artık öğrenildi kabul edilir ve pratikten çıkar)
  ///
  /// - BİLEMEDİM (correct = false):
  ///   masteryLevel 1 düşer (minimum 0).
  ///   Yeni nextReviewAt: +1 gün (ertesi gün tekrar).
  Future<void> submitAnswer(
    String wordId,
    int currentLevel,
    bool correct,
  ) async {
    final DateTime now = DateTime.now();

    if (correct) {
      final int newLevel = (currentLevel + 1).clamp(0, 5);
      Timestamp? nextReviewAt;

      switch (newLevel) {
        case 1:
          nextReviewAt = Timestamp.fromDate(now.add(const Duration(days: 2)));
          break;
        case 2:
          nextReviewAt = Timestamp.fromDate(now.add(const Duration(days: 4)));
          break;
        case 3:
          nextReviewAt = Timestamp.fromDate(now.add(const Duration(days: 7)));
          break;
        case 4:
          nextReviewAt = Timestamp.fromDate(now.add(const Duration(days: 14)));
          break;
        case 5:
        default:
          nextReviewAt = null; // Mastered, drop from practice
          break;
      }

      await _wordsCollection.doc(wordId).update({
        'masteryLevel': newLevel,
        'nextReviewAt': nextReviewAt,
      });
    } else {
      final int newLevel = (currentLevel - 1).clamp(0, 5);
      // Bilemedim: ertesi gün tekrar (+1 gün)
      final nextReviewAt = Timestamp.fromDate(now.add(const Duration(days: 1)));

      await _wordsCollection.doc(wordId).update({
        'masteryLevel': newLevel,
        'nextReviewAt': nextReviewAt,
      });
    }
  }

  // ---------------------------------------------------------------------------
  // DELETE
  // ---------------------------------------------------------------------------

  /// Permanently deletes the word document identified by [wordId].
  Future<void> deleteWord(String wordId) async {
    await _wordsCollection.doc(wordId).delete();
  }
}
