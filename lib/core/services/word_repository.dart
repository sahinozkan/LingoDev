import 'package:cloud_firestore/cloud_firestore.dart';

import '../models/word_model.dart';

/// Repository for CRUD operations on a user's word collection.
///
/// Firestore path: `users/{userId}/words/{wordId}`
class WordRepository {
  WordRepository({required this.userId})
      : _wordsCollection = FirebaseFirestore.instance
            .collection('users')
            .doc(userId)
            .collection('words');

  final String userId;

  final CollectionReference<Map<String, dynamic>> _wordsCollection;

  // ---------------------------------------------------------------------------
  // READ
  // ---------------------------------------------------------------------------

  /// Real-time stream of all words, ordered by [createdAt] descending.
  Stream<List<WordModel>> watchWords() {
    return _wordsCollection
        .orderBy('createdAt', descending: true)
        .snapshots()
        .map(
          (snapshot) =>
              snapshot.docs.map(WordModel.fromFirestore).toList(),
        );
  }

  // ---------------------------------------------------------------------------
  // CREATE
  // ---------------------------------------------------------------------------

  /// Adds [word] to Firestore. The document ID is auto-generated by Firestore.
  Future<void> addWord(WordModel word) async {
    await _wordsCollection.add(word.toFirestore());
  }

  // ---------------------------------------------------------------------------
  // UPDATE
  // ---------------------------------------------------------------------------

  /// Overwrites the Firestore document identified by [word.id].
  Future<void> updateWord(WordModel word) async {
    await _wordsCollection.doc(word.id).update(word.toFirestore());
  }

  // ---------------------------------------------------------------------------
  // DELETE
  // ---------------------------------------------------------------------------

  /// Permanently deletes the word document identified by [wordId].
  Future<void> deleteWord(String wordId) async {
    await _wordsCollection.doc(wordId).delete();
  }
}
